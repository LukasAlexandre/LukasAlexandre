"""Regenerate the GitHub README and its self-contained images. Offline by default."""
from __future__ import annotations

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET

from common import ROOT, THEMES, esc, load_json, safe_url


def picture(name: str, alt: str, width: str = "100%", mobile: bool = False, *, raster: bool = False) -> str:
    if raster:
        markup = picture(name, alt, width, mobile)
        import re
        markup = re.sub(r'([A-Za-z0-9/-]+)\.svg', lambda m: m[1] + ('.png' if m[1].endswith('-static') else '.gif'), markup)
        markup = re.sub(r'<source media="([^"]+)" srcset="([^"]+)\.gif">',
                        lambda m: f'<source media="{m[1]}" type="image/webp" srcset="{m[2]}.webp">' + m[0], markup)
        return markup.replace('<img ', f'<source media="(prefers-color-scheme: dark)" type="image/webp" srcset="./generated/dark/{name}.webp"><img ', 1)
    sources = []
    if mobile:
        for theme in THEMES:
            sources.append(f'<source media="(prefers-reduced-motion: reduce) and (prefers-color-scheme: {theme}) and (max-width: 600px)" srcset="./generated/{theme}/{name}-mobile-static.svg">')
    for theme in THEMES:
        sources.append(f'<source media="(prefers-reduced-motion: reduce) and (prefers-color-scheme: {theme})" srcset="./generated/{theme}/{name}-static.svg">')
    if mobile:
        for theme in THEMES:
            sources.append(f'<source media="(prefers-color-scheme: {theme}) and (max-width: 600px)" srcset="./generated/{theme}/{name}-mobile.svg">')
    sources.append(f'<source media="(prefers-color-scheme: light)" srcset="./generated/light/{name}.svg">')
    return ('<picture>' + ''.join(sources) +
            f'<img src="./generated/dark/{name}.svg" alt="{esc(alt)}" width="{width}"></picture>')


def readme() -> str:
    profile = load_json("config/profile.json")
    sections = [picture("hero", profile["name"] + " — Product & Software Engineering. Professional identity and engineering mission.", mobile=True),
                picture("activity", "Development Activity: real contribution totals, active days, current and longest streaks, last twelve months heatmap and monthly bars.", mobile=True),
                picture("ecosystem-header", "Engineering Ecosystem", mobile=True)]
    config = load_json("config/projects.json")
    projects = config['projects'] if isinstance(config, dict) else config
    public = {p['id']: p for p in projects if p.get('public') is True}
    rows = config.get('layout', {}).get('rows') if isinstance(config, dict) else None
    if rows is None:
        ids = list(public)
        rows = [ids[i:i+2] for i in range(0, len(ids), 2)]
    for row in rows:
        visible = [public[key] for key in row if key in public]
        if not visible:
            continue
        width = '49%' if len(visible) == 2 else ('32%' if len(visible) == 3 else '100%')
        cards = []
        for project in visible:
            card = picture('project-' + project['id'], project['name'] + ' — ' + project.get('description', ''), width, mobile=True, raster=project.get('media') == 'original-render')
            # Links require an explicit verified marker, not merely an address.
            url = safe_url(project.get('url')) if project.get('linkVerified', False) else None
            cards.append(f'<a href="{esc(url)}">{card}</a>' if url else card)
        sections.append('<p>' + '\n'.join(cards) + '</p>')
    sections += [picture("stack", "Technology Stack: TypeScript, JavaScript, Python, C#, React, HTML, CSS, Node.js, FastAPI, MySQL, PostgreSQL, Artificial Intelligence, Git, GitHub and Docker.", mobile=True),
                 picture("connections-header", "Professional Connections", mobile=True)]
    connections = []
    for c in profile["connections"]:
        card = picture("connection-" + c["id"], c["title"] + " — " + c["subtitle"], "49%")
        url = safe_url(c.get("url")) if c.get("verified", False) else None
        connections.append(f'<a href="{esc(url)}">{card}</a>' if url else card)
    for i in range(0, len(connections), 2):
        sections.append('<p>' + '\n'.join(connections[i:i + 2]) + '</p>')
    sections.append(picture("footer", "LKR — ENGINEERING INTELLIGENCE", mobile=True))
    return '<!-- Generated by python scripts/build.py. Edit config/ and scripts/. -->\n\n' + '\n\n'.join(sections) + '\n'


def validate_generated() -> None:
    for theme in THEMES:
        for path in sorted((ROOT / "generated" / theme).glob("*.svg")):
            node = ET.parse(path).getroot()
            if node.tag != '{http://www.w3.org/2000/svg}svg':
                raise ValueError(f"Not an SVG: {path}")
            for element in node.iter():
                tag = element.tag.rsplit('}', 1)[-1]
                if tag in {"script", "foreignObject", "image"}:
                    raise ValueError(f"Disallowed SVG element {tag}: {path}")
                for key, val in element.attrib.items():
                    if key.lower().startswith('on') or ('href' in key and not val.startswith('#')):
                        raise ValueError(f"External/active SVG content: {path}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--refresh', action='store_true', help='Fetch real public contributions with last-valid fallback')
    args = parser.parse_args()
    if args.refresh:
        import fetch_contributions
        _, fallback = fetch_contributions.refresh(load_json('config/profile.json')['login'])
        if fallback:
            print('WARNING: collection unavailable; preserved the last validated contribution cache.')
    for module in ('render_hero', 'render_activity', 'render_ecosystem', 'render_stack', 'render_connections'):
        __import__(module).render()
    validate_generated()
    markup = readme()
    (ROOT / 'README.md').write_text(markup, encoding='utf-8', newline='\n')
    (ROOT / 'preview').mkdir(exist_ok=True)
    (ROOT / 'preview/readme.html').write_text(markup, encoding='utf-8', newline='\n')
    print('Generated README, preview fragment and validated SVG images (offline unless --refresh).')


if __name__ == '__main__':
    main()
